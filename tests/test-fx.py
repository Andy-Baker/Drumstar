    r=await ev("(()=>{const t=__T.find(x=>x.id==='arp'); return [t.eqMidGain,t.eqMf,t._eqIn];})()")
    ok('EQ-Kurve: Mitten-Punkt ziehen hebt an und verschiebt', r[0]>3 and r[1]>0.5 and r[2], r)
