    await pg.click('#klRows .fxlsel >> nth=1 >> [data-op]'); await pg.click('#klRows .fxlsel .menu.open [data-v="8d"]'); await pg.wait_for_timeout(200)
    ok('Notenwert per LCD-Liste', await ev("fxDelay.div")=='8d')
